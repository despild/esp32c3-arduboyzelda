def pattern(rows,w,h):
    rows=rows.split('/');sw=max(map(len,rows));sh=len(rows)
    return [[int(rows[min(sh-1,y*sh//h)][min(len(rows[min(sh-1,y*sh//h)])-1,x*sw//w)]=='#') for x in range(w)] for y in range(h)]
def packed(a,w,h):
    return [sum((a[y][x] if y<h else 0)<<(y%8) for y in range(page*8,page*8+8)) for page in range((h+7)//8) for x in range(w)]
def emit(name,w,h,frames,masked=False):
    values=[w,h]
    for rows in frames:
        a=pattern(rows,w,h);values+=packed(a,w,h)
        if masked:
            m=[[int(any(a[yy][xx] for yy in range(max(0,y-1),min(h,y+2)) for xx in range(max(0,x-1),min(w,x+2)))) for x in range(w)] for y in range(h)]
            values+=packed(m,w,h)
    return 'static const uint8_t PROGMEM '+name+'[]={'+','.join(map(str,values))+'};\n'

