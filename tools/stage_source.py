"""Stage a single translation unit to avoid repeated Arduino header discovery.

Original .cpp files remain reviewable in src/. Only generated build inputs use
.impl.h files. File-local constants and enum members are renamed during staging.
"""
from pathlib import Path
import shutil
import re
ROOT=Path(__file__).resolve().parents[1]
def stage(dest):
    dest=Path(dest).resolve()
    if dest==ROOT/'src' or not any(part in ('firmware','build') for part in dest.parts):
        raise ValueError('Destination must be a generated firmware/build folder')
    dest.mkdir(parents=True,exist_ok=True)
    # Remove only prior generated C++ units, after checking each resolved path.
    for p in dest.rglob('*.cpp'):
        p.resolve().relative_to(dest)
        p.unlink()
    units=[]
    for p in sorted((ROOT/'src').rglob('*')):
        if not p.is_file():continue
        relative=p.relative_to(ROOT/'src');target=dest/relative
        target.parent.mkdir(parents=True,exist_ok=True)
        if p.suffix=='.cpp':
            target=target.with_suffix('.impl.h');text=p.read_text(encoding='utf-8')
            if p.name in ('snake.cpp','spike.cpp'):
                for symbol in ('PursueVelocity','Pursue'):
                    text=re.sub(r'\b'+symbol+r'\b',p.stem+'_'+symbol,text)
            target.write_text(text,encoding='utf-8');units.append(target.relative_to(dest).as_posix())
        else:shutil.copy2(p,target)
    (dest/'ArdAdventureUnity.cpp').write_text('// Generated by tools/stage_source.py\n'+'\n'.join('#include "'+p+'"' for p in units)+'\n',encoding='utf-8')
    return dest
